const assert = require('node:assert/strict');
const {rectanglesOverlap,overlapArea,intersectionRectangle,containsPoint,minimumTranslationVector,rectangleEdges,translateRectangle,clampRectangle} = require('./collision.js');
const a = {x:0,y:0,width:10,height:10};
assert.equal(rectanglesOverlap(a,{x:0,y:0,width:10,height:10}),true);
assert.equal(rectanglesOverlap(a,{x:9,y:0,width:10,height:10}),true);
assert.equal(rectanglesOverlap(a,{x:10,y:0,width:10,height:10}),false);
assert.equal(rectanglesOverlap(a,{x:0,y:10,width:10,height:10}),false);
assert.equal(rectanglesOverlap(a,{x:0,y:0,width:-1,height:10}),false);
assert.equal(rectanglesOverlap(a,{x:NaN,y:0,width:10,height:10}),false);
assert.equal(overlapArea(a,{x:0,y:0,width:10,height:10}),100);
assert.equal(overlapArea(a,{x:5,y:0,width:10,height:10}),50);
assert.equal(overlapArea(a,{x:10,y:0,width:10,height:10}),0);
assert.equal(overlapArea(a,{x:0,y:0,width:-1,height:10}),0);
assert.deepEqual(intersectionRectangle(a,{x:5,y:0,width:10,height:10}),{x:2.5,y:0,width:5,height:10});
assert.equal(intersectionRectangle(a,{x:10,y:0,width:10,height:10}),null);
assert.equal(containsPoint(a,{x:-5,y:5}),true);
assert.equal(containsPoint(a,{x:5.01,y:0}),false);
assert.equal(containsPoint(a,{x:'0',y:0}),false);
assert.deepEqual(minimumTranslationVector(a,{x:8,y:0,width:10,height:10}),{x:-2,y:0});
assert.deepEqual(minimumTranslationVector(a,{x:0,y:8,width:10,height:10}),{x:0,y:-2});
assert.equal(minimumTranslationVector(a,{x:10,y:0,width:10,height:10}),null);
assert.equal(rectangleEdges({x:0,y:0,width:0,height:1}),null);
assert.equal(rectanglesOverlap(null,a),false);
assert.equal(overlapArea({x:0,y:0,width:10,height:10},{x:5,y:5,width:10,height:10}),25);
assert.deepEqual(intersectionRectangle({x:0,y:0,width:10,height:10},{x:5,y:5,width:10,height:10}),{x:2.5,y:2.5,width:5,height:5});
assert.deepEqual(minimumTranslationVector({x:0,y:0,width:10,height:10},{x:5,y:5,width:10,height:10}),{x:-5,y:0});
assert.equal(containsPoint({x:0,y:0,width:10,height:10},{x:5,y:-5}),true);
assert.deepEqual(translateRectangle(a,{x:3,y:-2}),{x:3,y:-2,width:10,height:10});
assert.equal(translateRectangle(a,{x:Infinity,y:0}),null);
assert.deepEqual(clampRectangle({x:20,y:-20,width:4,height:4},{x:0,y:0,width:10,height:10}),{x:3,y:-3,width:4,height:4});
assert.equal(clampRectangle({x:0,y:0,width:12,height:4},{x:0,y:0,width:10,height:10}),null);
console.log('28 collision geometry checks passed');
